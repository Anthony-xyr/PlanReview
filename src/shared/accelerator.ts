type ShortcutInput = Pick<KeyboardEvent, 'code' | 'ctrlKey' | 'altKey' | 'shiftKey' | 'metaKey' | 'isComposing'>

const namedKeys: ReadonlyMap<string, string> = new Map([
  ['Space', 'Space'], ['Enter', 'Return'], ['Backspace', 'Backspace'], ['Delete', 'Delete'], ['Insert', 'Insert'],
  ['ArrowUp', 'Up'], ['ArrowDown', 'Down'], ['ArrowLeft', 'Left'], ['ArrowRight', 'Right'],
  ['Home', 'Home'], ['End', 'End'], ['PageUp', 'PageUp'], ['PageDown', 'PageDown'],
  ['Minus', '-'], ['Equal', '='], ['Comma', ','], ['Period', '.'], ['Slash', '/'], ['Semicolon', ';'],
  ['Quote', "'"], ['Backquote', '`'], ['BracketLeft', '['], ['BracketRight', ']'], ['Backslash', '\\'],
  ['NumpadDecimal', 'numdec'], ['NumpadAdd', 'numadd'], ['NumpadSubtract', 'numsub'],
  ['NumpadMultiply', 'nummult'], ['NumpadDivide', 'numdiv']
])

/** Translate physical keys rather than the characters generated by Option, Shift or an active layout. */
export function toAccelerator(event: ShortcutInput, platform: string): string | null {
  if (event.isComposing) return null
  const mac = platform === 'darwin'
  const mods = [
    event.ctrlKey && 'Ctrl',
    event.altKey && (mac ? 'Option' : 'Alt'),
    event.shiftKey && 'Shift',
    event.metaKey && (mac ? 'Command' : 'Super')
  ].filter(Boolean)
  if (!mods.length) return null

  const { code } = event
  const key = /^(?:Key([A-Z])|Digit([0-9])|Numpad([0-9])|(F(?:[1-9]|1[0-9]|2[0-4])))$/.exec(code)
  const name = key ? key[1] || key[2] || (key[3] ? `num${key[3]}` : key[4]) : namedKeys.get(code)
  return name ? [...mods, name].join('+') : null
}
